-- 12. Learner Sessions Table (bearer tokens for the student portal)
-- Only the SHA-256 digest of a token is stored, so a database copy cannot be replayed
-- as a live session. Logout and password reset stamp revoked_at rather than deleting.
CREATE TABLE IF NOT EXISTS learner_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    learner_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    last_seen_at TIMESTAMP NULL,
    revoked_at TIMESTAMP NULL,
    CONSTRAINT fk_learner_session_learner FOREIGN KEY (learner_id) REFERENCES learners(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_learner_sessions_token_hash ON learner_sessions(token_hash);
CREATE INDEX IF NOT EXISTS idx_learner_sessions_learner ON learner_sessions(learner_id);

-- 13. Assessor and moderator assignments (Phase 1)
