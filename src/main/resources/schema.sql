CREATE INDEX IF NOT EXISTS idx_assessor_assignment_assessor ON assessor_assignments(assessor_id);
CREATE INDEX IF NOT EXISTS idx_assessor_assignment_learner ON assessor_assignments(learner_id);
CREATE INDEX IF NOT EXISTS idx_assessor_assignment_category ON assessor_assignments(category_id);

